"""Catalog data and isolated integrations used by catalog views."""

import base64
import io
import json

import requests
from PIL import Image, ImageOps, UnidentifiedImageError


class FoodAnalysisError(Exception):
    """A safe, user-facing food analysis failure."""


FOOD_ANALYSIS_SCHEMA = {
    "type": "object",
    "properties": {
        "meal_name": {"type": "string"},
        "total_calories": {"type": "integer", "minimum": 0},
        "confidence": {
            "type": "string",
            "enum": ["منخفضة", "متوسطة", "عالية"],
        },
        "items": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "name": {"type": "string"},
                    "portion": {"type": "string"},
                    "calories": {"type": "integer", "minimum": 0},
                },
                "required": ["name", "portion", "calories"],
                "additionalProperties": False,
            },
        },
        "assumptions": {
            "type": "array",
            "items": {"type": "string"},
        },
        "notes": {
            "type": "array",
            "items": {"type": "string"},
        },
    },
    "required": [
        "meal_name",
        "total_calories",
        "confidence",
        "items",
        "assumptions",
        "notes",
    ],
    "additionalProperties": False,
}


def _prepare_food_image(uploaded_photo):
    try:
        uploaded_photo.seek(0)
        with Image.open(uploaded_photo) as source_image:
            image = ImageOps.exif_transpose(source_image).convert("RGB")
            image.thumbnail((1600, 1600), Image.Resampling.LANCZOS)
            output = io.BytesIO()
            image.save(output, format="JPEG", quality=88, optimize=True)
    except (OSError, UnidentifiedImageError) as error:
        raise FoodAnalysisError("تعذر قراءة الصورة المرفوعة.") from error

    return base64.b64encode(output.getvalue()).decode("ascii")


def _extract_response_text(response_data):
    for output_item in response_data.get("output", []):
        if output_item.get("type") != "message":
            continue
        for content_item in output_item.get("content", []):
            if content_item.get("type") == "output_text":
                return content_item.get("text", "")
    raise FoodAnalysisError("لم ترجع خدمة التحليل نتيجة قابلة للقراءة.")


def analyze_food_image(
    uploaded_photo,
    meal_context,
    *,
    api_key,
    model,
    timeout=75,
):
    """Estimate meal calories from an uploaded image via Responses API."""
    image_base64 = _prepare_food_image(uploaded_photo)
    context_text = meal_context.strip() or "لا توجد معلومات إضافية."
    prompt = (
        "حلل صورة الطعام كتقدير تثقيفي للسعرات الحرارية. "
        "حدد كل مكوّن ظاهر، وقدّر حصته وسعراته، ثم احسب المجموع. "
        "اذكر افتراضاتك بوضوح ولا تدّعِ دقة مخبرية. إذا لم تكن الصورة "
        "لطعام صالح للتحليل، أرجع مجموعًا يساوي صفرًا وثقة منخفضة واشرح "
        "ذلك في الملاحظات. أجب بالعربية فقط. معلومات المستخدم: "
        f"{context_text}"
    )
    payload = {
        "model": model,
        "store": False,
        "input": [
            {
                "role": "user",
                "content": [
                    {"type": "input_text", "text": prompt},
                    {
                        "type": "input_image",
                        "image_url": f"data:image/jpeg;base64,{image_base64}",
                        "detail": "high",
                    },
                ],
            }
        ],
        "text": {
            "format": {
                "type": "json_schema",
                "name": "food_calorie_estimate",
                "strict": True,
                "schema": FOOD_ANALYSIS_SCHEMA,
            }
        },
    }

    try:
        response = requests.post(
            "https://api.openai.com/v1/responses",
            headers={
                "Authorization": f"Bearer {api_key}",
                "Content-Type": "application/json",
            },
            json=payload,
            timeout=timeout,
        )
        response.raise_for_status()
        result = json.loads(_extract_response_text(response.json()))
    except requests.Timeout as error:
        raise FoodAnalysisError(
            "استغرق التحليل وقتًا طويلًا. حاول مرة أخرى بصورة أصغر."
        ) from error
    except requests.RequestException as error:
        raise FoodAnalysisError(
            "تعذر الاتصال بخدمة تحليل الصور الآن. حاول لاحقًا."
        ) from error
    except (ValueError, TypeError, json.JSONDecodeError) as error:
        raise FoodAnalysisError(
            "وصلت نتيجة غير مكتملة من خدمة التحليل. حاول مرة أخرى."
        ) from error

    return result


